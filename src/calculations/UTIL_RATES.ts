export function findElectricRate(year: number, horse_power: number) { // вспомогательная функция для определения ставки электромобилей
  // Определяем категорию (новый или старый автомобиль)
  const isNew = year < 3;

  const ratesCategory = isNew 
    ? UTILIZATION_RATES_ELECTRICITY.new 
    : UTILIZATION_RATES_ELECTRICITY.old;

  // Ищем подходящий диапазон лошадиных сил
  const rateObj = ratesCategory.find(rate => 
    horse_power >= rate.horse_power_range[0] && 
    horse_power <= rate.horse_power_range[1]
  );

  // Если нашли - возвращаем ставку, иначе используем максимальную ставку как запасной вариант
  if (rateObj) {
    return rateObj.rate;
  } else {
    console.warn(`Не найдена ставка для электромобиля: год=${year}, л.с.=${horse_power}`);
    return isNew ? 182.40 : 239.04; // Максимальные ставки как fallback
  }
}

export function findCombustionRate(year: number, engine: number, horse_power: number) { // вспомогательная функция для определения ставки остальный автомобилей
  // Определяем категорию (новый или старый автомобиль)
  const isNew = year < 3;

  const ratesCategory = isNew 
    ? UTILIZATION_RATES_COMBUSTION.new 
    : UTILIZATION_RATES_COMBUSTION.old;

  // Ищем подходящий диапазон объема двигателя
  const engineRangeObj = ratesCategory.find(range => 
    engine >= range.engineRange[0] && 
    engine <= range.engineRange[1]
  );

  // Если не нашли подходящий диапазон объема
  if (!engineRangeObj) {
    console.warn(`Не найден диапазон объема двигателя: ${engine} куб.см`);
    // Используем максимальную ставку как запасной вариант
    return isNew ? 229.08 : 344.28;
  }

  // Ищем подходящий диапазон лошадиных сил в найденном диапазоне объема
  const horsePowerRateObj = engineRangeObj.rates.find(rate => 
    horse_power >= rate.horse_power_range[0] && 
    horse_power <= rate.horse_power_range[1]
  );

  // Если нашли - возвращаем ставку, иначе используем максимальную ставку из этого диапазона
  if (horsePowerRateObj) {
    return horsePowerRateObj.rate;
  } else {
    console.warn(`Не найдена ставка для ДВС: объем=${engine}, л.с.=${horse_power}`);
    // Берем последнюю (максимальную) ставку из этого диапазона объема
    const lastRate = engineRangeObj.rates[engineRangeObj.rates.length - 1];
    return lastRate.rate;
  }
}